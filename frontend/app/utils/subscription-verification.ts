/** Состояние шага «введите код из письма» при подписке на вакансии */
export interface SubscribeVerification {
  /** Шаг с вводом кода показан (письмо с кодом уже отправлено) */
  active: boolean
  /** Адрес, на который отправлен код */
  email: string
  /** Идёт проверка кода */
  loading: boolean
  /** Идёт повторная отправка кода */
  resending: boolean
  /** Сообщение об ошибке под полем кода */
  error: string
  /** Сколько секунд осталось до возможности отправить код ещё раз */
  resendIn: number
}
